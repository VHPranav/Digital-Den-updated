// Generates src/components/home/regionMapData.ts: SVG paths for a recognisable world map
// (all countries) plus the approved Digital Den regions, which are filled in purple.
// Run: node scripts/build-region-map.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const world = require('world-atlas/countries-110m.json');
const countries = feature(world, world.objects.countries).features.filter((f) => f.properties.name !== 'Antarctica');

const W = 1000;
const H = 500;
const projection = geoNaturalEarth1().fitExtent([[6, 6], [W - 6, H - 6]], { type: 'FeatureCollection', features: countries });
const path = geoPath(projection);
const round = (d) => d.replace(/(\d+\.\d{1})\d+/g, '$1');

// Approved regions only (Home Page notes): Montenegro is the hub.
const REGIONS = [
  { id: 'montenegro', name: 'Montenegro', countries: ['Montenegro'], at: [19.3, 42.7], hub: true },
  { id: 'western-balkans', name: 'Western Balkans', countries: ['Serbia', 'Bosnia and Herz.', 'Albania', 'Macedonia', 'Kosovo'], at: [21.6, 44.9] },
  { id: 'united-states', name: 'United States', countries: ['United States of America'], at: [-98.35, 39.5] },
  { id: 'benelux', name: 'Benelux', countries: ['Belgium', 'Netherlands', 'Luxembourg'], at: [4.9, 50.9] },
  { id: 'jordan', name: 'Jordan', countries: ['Jordan'], at: [36.4, 31.2] },
];

// United States: only the contiguous mainland is highlighted; Alaska and Hawaii stay grey
// (accurate, but they otherwise dominate the map).
const isMainlandUS = (poly) => poly[0].every(([lon, lat]) => lon > -130 && lon < -60 && lat > 23 && lat < 50);
const usa = countries.find((f) => f.properties.name === 'United States of America');
const usPolys = usa.geometry.type === 'MultiPolygon' ? usa.geometry.coordinates : [usa.geometry.coordinates];
const usMainland = { ...usa, geometry: { type: 'MultiPolygon', coordinates: usPolys.filter(isMainlandUS) } };
const usOutlying = { ...usa, geometry: { type: 'MultiPolygon', coordinates: usPolys.filter((p) => !isMainlandUS(p)) } };
const shapeOf = (f) => (f === usa ? usMainland : f);

const highlighted = new Set(REGIONS.flatMap((r) => r.countries));
const land = round(countries.filter((f) => !highlighted.has(f.properties.name)).map((f) => path(f)).join('') + path(usOutlying));

const regions = REGIONS.map((r) => {
  const d = round(countries.filter((f) => r.countries.includes(f.properties.name)).map((f) => path(shapeOf(f))).join(''));
  const [x, y] = projection(r.at);
  return { id: r.id, name: r.name, hub: !!r.hub, d, x: +x.toFixed(1), y: +y.toFixed(1) };
});

const out = `// Generated by scripts/build-region-map.mjs — do not edit by hand.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const LAND_PATH = ${JSON.stringify(land)};
export const REGIONS = ${JSON.stringify(regions, null, 2)} as const;
`;
writeFileSync(new URL('../src/components/home/regionMapData.ts', import.meta.url), out);
console.log('regionMapData.ts written:', (out.length / 1024).toFixed(1), 'KB');
